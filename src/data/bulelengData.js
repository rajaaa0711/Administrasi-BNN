// Helper: Ambil seluruh daftar 148 desa se-Kabupaten Buleleng dengan info kecamatannya
export const getAllDesaBuleleng = () => {
  const all = [];
  Object.keys(desaBuleleng).forEach((kecKey) => {
    const kecLabel = kecamatanList.find((k) => k.val === kecKey)?.label || kecKey;
    desaBuleleng[kecKey].forEach((desaName) => {
      all.push({
        name: desaName,
        kecamatanKey: kecKey,
        kecamatanLabel: kecLabel,
      });
    });
  });
  return all;
};
